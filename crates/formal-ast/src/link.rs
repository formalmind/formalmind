//! Linking models into a world: interfaces replaced by the contracts that implement them.
//!
//! Each contract's model is generic over a world `σ` (its `Ext` is a lens onto its own `State`). The linker puts
//! every contract's storage in one `World`, gives each an address, and instantiates every `Ext` so that a call
//! through an interface to a bound address runs the implementation's model, with `msg.sender` set to the caller
//! and `address(this)` to the callee. Calls nest through `exts n`: each one uses up a level, and level 0 reverts
//! ("call depth"), the way the EVM bounds call depth. Everything not bound stays a field of `Open`.

use crate::lean::{ident, Parts, PRELUDE};
use std::collections::BTreeSet;
use std::fmt::Write as _;

pub struct Linked {
    pub text: String,
    /// (caller, Ext field, callee) for every bound call.
    pub bound: Vec<(String, String, String)>,
}

fn field_name(contract: &str) -> String {
    let mut c = contract.chars();
    match c.next() {
        Some(f) => ident(&(f.to_lowercase().collect::<String>() + c.as_str())),
        None => "c".into(),
    }
}

fn bare(name: &str) -> &str {
    name.trim_matches(|c| c == '«' || c == '»')
}

/// `O`'s field for a contract's `Ext` field, quoted as one name.
fn open_name(member_field: &str, ext_field: &str) -> String {
    ident(&format!("{}_{}", bare(member_field), bare(ext_field)))
}

fn proj(t: &str, i: usize, n: usize) -> String {
    if n == 1 {
        return t.to_string();
    }
    let mut s = format!("({t})");
    for _ in 0..i {
        s.push_str(".2");
    }
    if i < n - 1 {
        s.push_str(".1");
    }
    s
}

pub fn link(members: &[Parts]) -> Linked {
    let n = members.len();
    let names: Vec<String> = members.iter().map(|m| ident(&m.contract)).collect();
    let fields: Vec<String> = members.iter().map(|m| field_name(&m.contract)).collect();
    let mut out = String::new();
    let _ = writeln!(out, "/-\n  Generated by formal-ast: a world of {} linked from solc's AST. Don't edit: regenerate.\n-/", members.iter().map(|m| m.contract.as_str()).collect::<Vec<_>>().join(", "));
    out.push_str(PRELUDE);
    let _ = writeln!(out, "\nnamespace Model\nopen FormalAst\nset_option linter.unusedVariables false\nset_option maxHeartbeats 400000\n");

    // Structs are shared: a PoolKey is the same type in every contract's model.
    let mut seen = BTreeSet::new();
    for m in members {
        for (name, text) in &m.structs {
            if seen.insert(name.clone()) {
                out.push_str(text);
            }
        }
    }
    for (m, name) in members.iter().zip(&names) {
        let _ = writeln!(out, "namespace {name}\n{}end {name}\n", m.body);
    }

    let _ = writeln!(out, "/-- The world: every linked contract's storage. -/\nstructure World where");
    for (name, f) in names.iter().zip(&fields) {
        let _ = writeln!(out, "  {f} : {name}.State");
    }
    let _ = writeln!(out, "deriving Inhabited\n\n/-- Where each contract lives. -/\nstructure Addrs where");
    for f in &fields {
        let _ = writeln!(out, "  {f} : Nat");
    }

    // Bindings, by selector as the EVM dispatches: a call through any interface goes to every member with a
    // translated public function of that name and those parameter types, chosen by the target address.
    let mut bound = vec![];
    let mut binding = vec![]; // per member: per ext field, (targets [(member j, lean fn)], arity, view)
    for (i, m) in members.iter().enumerate() {
        let mut b = vec![];
        for (fname, _, _) in &m.ext {
            let call = m.calls.iter().find(|c| &c.field == fname);
            let targets: Vec<(usize, String)> = call
                .map(|c| {
                    members
                        .iter()
                        .enumerate()
                        .filter(|(j, _)| *j != i)
                        .filter_map(|(j, other)| {
                            let e = other.entries.iter().find(|e| e.name == c.function && e.params == c.params)?;
                            Some((j, e.lean.clone()?))
                        })
                        .collect()
                })
                .unwrap_or_default();
            for (j, _) in &targets {
                bound.push((m.contract.clone(), fname.clone(), members[*j].contract.clone()));
            }
            b.push(call.filter(|_| !targets.is_empty()).map(|c| (targets, c.params.len(), c.view)));
        }
        binding.push(b);
    }

    let _ = writeln!(out, "\n/-- Everything still open in the world: each contract's `Ext` fields that no binding covers. -/\nstructure Open where");
    for (i, m) in members.iter().enumerate() {
        for (fname, ty, why) in &m.ext {
            let _ = writeln!(out, "  /-- {}: {why} -/\n  {} : {}", m.contract, open_name(&fields[i], fname), ty.replace('σ', "World"));
        }
    }

    let tuple_ty = members.iter().map(|m| format!("{}.Ext World", ident(&m.contract))).collect::<Vec<_>>().join(" × ");
    let _ = writeln!(out, "\n/-- Every contract's `Ext` in the world, allowing `n` more nested calls between linked contracts. -/\ndef exts (A : Addrs) (O : Open) : Nat → {tuple_ty}");
    for depth in ["0", "n + 1"] {
        let _ = writeln!(out, "  | {depth} =>");
        let mut items = vec![];
        for (i, m) in members.iter().enumerate() {
            let fi = &fields[i];
            // Fields line up under the first one (Lean reads `{ … }` by column).
            let mut s = format!("{}{{ get := fun w => w.{fi}, set := fun w s => {{ w with {fi} := s }}", if i == 0 { "    (" } else { "     " });
            for (k, (fname, _, _)) in m.ext.iter().enumerate() {
                let open = format!("O.{}", open_name(fi, fname));
                let v = match &binding[i][k] {
                    None => open,
                    Some((targets, arity, view)) => {
                        let args: Vec<String> = (0..*arity).map(|a| format!("a{a}")).collect();
                        let a = args.join(" ");
                        // The fallback when the address is none of the bound members: the open behaviour.
                        let mut body = if *view { format!("{open} env w addr {a}") } else { format!("{open} addr {a}") };
                        for (j, lean) in targets.iter().rev() {
                            let fj = &fields[*j];
                            let callee = format!("{}.{lean} {} {a}", names[*j], proj("exts A O n", *j, n));
                            let run = match (*view, depth) {
                                (false, "0") => "throw ⟨\"call depth\"⟩".to_string(),
                                (false, _) => format!("callAs A.{fi} A.{fj} ({callee})"),
                                (true, "0") => ".error ⟨\"call depth\"⟩".to_string(),
                                (true, _) => format!("runView ({callee}) {{ env with sender := A.{fi}, self := A.{fj}, value := 0 }} w"),
                            };
                            body = format!("if addr = A.{fj} then {run} else {body}");
                        }
                        if *view { format!("fun env w addr {a} => {body}") } else { format!("fun addr {a} => {body}") }
                    }
                };
                let _ = write!(s, ",\n       {fname} := {v}");
            }
            s.push_str(" }");
            items.push(s);
        }
        let _ = writeln!(out, "{})", items.join(",\n"));
    }
    let _ = writeln!(out, "\nend Model");
    Linked { text: out, bound }
}
